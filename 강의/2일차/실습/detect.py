# 아래는 채점·실행에 쓰는 부분입니다. 고치지 않아도 됩니다.
# =============================================================================
def detect(values: list[float | None], window: int = 60, k: float = 3.0) -> list[bool]:
    """한 설비, 한 항목(온도 또는 진동)의 시계열에 이상감지를 돌린다.

    values 와 같은 길이의 True/False 리스트를 돌려준다.
    """
    cleaned = handle_missing(values)
    flags: list[bool] = []

    for i in range(len(cleaned)):
        stats = window_stats(cleaned, i, window)
        cur = cleaned[i]

        if stats is None or cur is None:
            flags.append(False)          # 아직 판단할 수 없는 구간
            continue

        mean, std = stats
        flags.append(bool(is_anomaly(cur, mean, std, k)))

    return flags
