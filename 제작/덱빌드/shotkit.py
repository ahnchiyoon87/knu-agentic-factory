# -*- coding: utf-8 -*-
"""실제 화면(PNG)을 슬라이드에 박고, 누를 자리에 붉은 표시를 얹는다.

    화면("완성_홈")                      → 화면만
    화면("만들기_04_표메뉴",
         (6, 22, 88, 16, "1"))          → 그 자리에 붉은 상자 + 번호 뱃지

좌표는 **화면 이미지 기준 백분율** (왼쪽, 위, 너비, 높이) 로 적는다.
픽셀이 아니라 %  — 화면을 다시 뽑아 크기가 달라져도 표시가 안 어긋난다.

왜 그림이 아니라 캡처인가
    학생은 진짜 노션을 보면서 따라온다. 흉내 낸 그림은 실제와 조금씩 달라서
    「내 화면엔 이게 없는데」로 이어진다. 화면은 캡처, 설명은 그 화면에 대해서만.
"""

from __future__ import annotations

import base64
import functools
import io
import struct
from pathlib import Path

그림 = Path(__file__).resolve().parents[2] / "강의" / "그림"


@functools.lru_cache(maxsize=64)
def _읽기(경로: str) -> tuple[str, int, int]:
    """base64 와 함께 **가로·세로 픽셀**을 돌려준다.

    비율을 CSS 에 못 박아야 화면이 본문 상자 높이에 정확히 맞는다.
    비율 없이 max-height 만 주면 상자를 넘쳐 제목·각주를 침범한다(실제로 겪음).
    """
    p = 그림 / 경로
    if not p.is_file():
        raise SystemExit(f"화면 그림이 없습니다: {p}\n"
                         f"  노션 화면 —  python 제작/빌드도구/노션화면추출.py\n"
                         f"  그 밖 —  실제로 캡처해서 강의/그림/ 에 두세요")
    raw = p.read_bytes()
    # PNG 머리(IHDR)에서 크기를 직접 읽는다 — 이것 때문에 Pillow 를 끌어오지 않는다
    w, h = struct.unpack(">II", raw[16:24])
    return base64.b64encode(raw).decode("ascii"), w, h


여백 = 0.6        # 상자를 대상보다 이만큼(%) 키운다 — 크면 옆 요소를 문다
최소간격 = 1.0     # 세로로 이웃한 상자 사이에 이만큼(%)은 비운다
최소폭 = 74.0      # 잘라낸 그림이 원본의 이만큼(%)보다 좁아지지 않게 — 맥락 보존
최소높이 = 88.0    # 낮게 잡으면 자른 자리가 글자 한가운데를 지나 반 토막이 보인다


def _겹침(a, b, 틈=0.0):
    return (a[0] < b[0] + b[2] + 틈 and b[0] < a[0] + a[2] + 틈
            and a[1] < b[1] + b[3] + 틈 and b[1] < a[1] + a[3] + 틈)


def _다듬기(항목, 이름=""):
    """여백을 주고 화면 밖으로 나가지 않게 자른다. 상자는 **옮기지 않는다.**

    예전에는 겹치면 뒤 상자를 아래로 밀고 높이를 깎았다. 그러면 상자가 납작한
    선이 되어 **아무것도 가리키지 않는 자국**만 남는다. 실제로 그렇게 나갔다.
    대상 위치는 원본에서 계산한 값이라 정확하다 — 그걸 억지로 옮기면 안 된다.

    겹치면 먼저 여백을 줄여 보고, 그래도 겹치면 **빌드를 멈춘다.**
    (가리킬 대상을 다시 고르거나 하나로 묶으라는 뜻이다)
    """
    def 여백주기(폭):
        r = []
        for x, y, w, h, 뱃지 in 항목:
            x2, y2 = x + w, y + h
            r.append([max(0.5, x - 폭), max(0.5, y - 폭),
                      min(99.5, x2 + 폭) - max(0.5, x - 폭),
                      min(99.5, y2 + 폭) - max(0.5, y - 폭), 뱃지])
        return r

    for 폭 in (여백, 여백 / 2, 0.0):
        결과 = 여백주기(폭)
        나쁨 = [(a, b) for a in range(len(결과)) for b in range(a + 1, len(결과))
                if _겹침(결과[a], 결과[b], 최소간격 if 폭 else 0.0)]
        if not 나쁨:
            return 결과

    a, b = 나쁨[0]
    raise SystemExit(
        f"강조 상자가 겹칩니다 ({이름}: {a + 1}번과 {b + 1}번)\n"
        f"    {[round(v, 1) for v in 결과[a][:4]]}  ↔  {[round(v, 1) for v in 결과[b][:4]]}\n"
        f"  상자를 옮기면 납작해져 아무것도 안 가리키게 됩니다.\n"
        f"  가리킬 대상을 **하나로 묶거나** 한쪽을 빼세요 (노션좌표뽑기.py 의 대상 목록).")


def _잘라내기(경로: str, 항목, 여유: float, 최소세로: float | None = None,
              최소가로: float | None = None, 기준=None):
    """표시한 자리만 남기고 잘라, 그 부분이 크게 그려지게 한다.

    화면 전체를 슬라이드 한쪽에 넣으면 0.3~0.6 배로 줄어서, 원본의 작은 글자가
    4~9px 로 그려진다. 강의장 뒷자리에서는 무엇을 누르라는 건지 안 보인다.
    **볼 곳만 남기면 같은 자리에 훨씬 크게 들어간다.**
    잘린 만큼 표시 좌표도 새 그림 기준으로 다시 계산해 돌려준다.
    """
    from PIL import Image

    p = 그림 / 경로
    im = Image.open(p)
    W, H = im.size

    # 위쪽 여유를 넉넉히 둔다 — 창 제목·표 머리 같은 **여기가 어디인지** 알려 주는
    # 것이 대개 위에 있다. 바싹 자르면 글자는 커지지만 무슨 화면인지 모르게 된다.
    잴것 = 기준 if 기준 else 항목
    x1 = max(0.0, min(t[0] for t in 잴것) - 여유)
    y1 = max(0.0, min(t[1] for t in 잴것) - 여유 * 2.2)
    x2 = min(100.0, max(t[0] + t[2] for t in 잴것) + 여유)
    y2 = min(100.0, max(t[1] + t[3] for t in 잴것) + 여유)

    # 너무 잘게 자르지 않는다 — 조각만 남으면 맥락이 사라진다.
    # 다만 한 장에 캡처 둘을 나란히 놓는 자리에서는 이 하한이 오히려 글자를 죽인다.
    # 폭이 반으로 줄어드는데 원본의 74% 를 남기면 0.3 배로 그려진다 — 그때만 낮춘다.
    가로한도 = 최소폭 if 최소가로 is None else 최소가로
    if x2 - x1 < 가로한도:
        가운데 = (x1 + x2) / 2
        x1, x2 = max(0.0, 가운데 - 가로한도 / 2), min(100.0, 가운데 + 가로한도 / 2)
        if x2 - x1 < 가로한도:                   # 가장자리에 붙었으면 반대쪽으로 넓힌다
            x1, x2 = (0.0, 가로한도) if x1 <= 0.01 else (100.0 - 가로한도, 100.0)
    세로한도 = 최소높이 if 최소세로 is None else 최소세로
    if y2 - y1 < 세로한도:
        가운데 = (y1 + y2) / 2
        y1, y2 = max(0.0, 가운데 - 세로한도 / 2), min(100.0, 가운데 + 세로한도 / 2)
        if y2 - y1 < 세로한도:
            y1, y2 = (0.0, 세로한도) if y1 <= 0.01 else (100.0 - 세로한도, 100.0)

    box = (round(x1 / 100 * W), round(y1 / 100 * H),
           round(x2 / 100 * W), round(y2 / 100 * H))
    잘린것 = im.convert("RGB").crop(box)

    새폭, 새높이 = (x2 - x1), (y2 - y1)
    옮김 = [((t[0] - x1) / 새폭 * 100, (t[1] - y1) / 새높이 * 100,
             t[2] / 새폭 * 100, t[3] / 새높이 * 100, t[4]) for t in 항목]

    buf = io.BytesIO()
    잘린것.save(buf, format="PNG", optimize=True)
    return base64.b64encode(buf.getvalue()).decode("ascii"), 옮김


# 레이아웃별로 화면에 주어진 자리 (CSS 와 맞춰 둔다)
#   step  1600 - 좌우76×2 - 글칸480 - 틈40 = 928     shot  980     full  1448
#   반    한 장에 캡처 둘을 나란히 놓을 때 (928 - 틈28) / 2
# 세로 584 = 본문 영역 y 193~777 (강사가 1~17장에서 손으로 맞춘 자리를 실측한 값)
#   graph 는 글칸(580)과 틈(64)을 뺀 나머지 — 글 왼쪽 · 화면 오른쪽인 장
자리크기 = {"step": (924, 584), "shot": (976, 584), "full": (1448, 584),
            "반": (448, 584), "graph": (804, 584)}


def 나란히(*화면들: str) -> str:
    """작은 캡처 둘을 한 줄에 — 「누르는 곳」과 「그 결과」가 둘 다 조각일 때만."""
    return '<div class="둘">' + "".join(화면들) + "</div>"


def 화면(이름: str, *표시, 폴더: str = "노션", 확대: bool = False,
         여유: float = 6.0, 조망: bool = False,
         최소세로: float | None = None, 최소가로: float | None = None,
         자르기=None, 자리: str = "step") -> str:
    """이름.png 를 박고, 표시마다 붉은 상자를 얹은 HTML 을 돌려준다.

    표시 = (왼쪽%, 위%, 너비%, 높이%) 또는 (…, "뱃지글자")
      좌표는 **대상 요소 그대로** 적는다. 여백과 겹침 정리는 `_다듬기` 가 한다.
      뱃지는 상자 **안쪽** 위 왼쪽에 놓는다 — 밖에 두면 화면 여백에 떠 버린다.
    """
    항목 = [(t[0], t[1], t[2], t[3], t[4] if len(t) > 4 else None) for t in 표시]
    # 뱃지에 ①②③ 같은 **원문자**를 넣으면 주황 원 안에 흰 동그라미가 또 생긴다.
    # 실제로 그렇게 나갔다. 맨 숫자만 받는다.
    for t in 항목:
        if t[4] and any(c in "①②③④⑤⑥⑦⑧⑨❶❷❸" for c in t[4]):
            raise SystemExit(f"뱃지에 원문자를 쓰지 마세요 ({이름}: {t[4]}) — "
                             f'"1" 처럼 맨 숫자로 적습니다. 동그라미는 CSS 가 그립니다.')
    # 자르기 = **상자를 그리지 않고** 볼 곳만 남긴다.
    #   완성 화면처럼 가리킬 데는 없지만 아래쪽만 크게 보여야 할 때 쓴다.
    #   상자를 넣어 자르면 아무것도 안 가리키는 주황 테두리가 남는다.
    if 확대 and (항목 or 자르기):
        기준 = [자르기] if 자르기 else None
        자료, 항목 = _잘라내기(f"{폴더}/{이름}.png", 항목 or [], 여유,
                              최소세로, 최소가로, 기준)
        from PIL import Image
        폭, 높이 = Image.open(그림 / f"{폴더}/{이름}.png").size   # 잘린 크기는 아래서 다시 잰다
        import base64 as _b
        폭, 높이 = Image.open(io.BytesIO(_b.b64decode(자료))).size
    else:
        자료, 폭, 높이 = _읽기(f"{폴더}/{이름}.png")

    # **작은 캡처는 키운다.** 원본 크기 그대로 두면 사이드바 조각 같은 그림이
    # 슬라이드 구석에 좁쌀만 하게 붙는다 (실제로 그렇게 나갔다).
    # 주어진 자리(가로·세로) 안에서 비율을 지키며 꽉 채운다.
    가용폭, 가용높이 = 자리크기.get(자리, 자리크기["step"])
    배 = min(가용폭 / 폭, 가용높이 / 높이)
    그린폭 = round(폭 * 배)
    크기 = f'style="width:{그린폭}px"'

    img = f'<img src="data:image/png;base64,{자료}" alt="">'
    정리 = _다듬기(항목, 이름)

    def _빈자리(가로, 세로, 나): # 그 점이 **다른 상자 안**이면 못 쓴다
        for j, (x2, y2, w2, h2, _) in enumerate(정리):
            if j != 나 and x2 - 1 <= 가로 <= x2 + w2 + 1 and y2 - 1 <= 세로 <= y2 + h2 + 3:
                return False
        return True

    상자 = ""
    for i, (x, y, w, h, 뱃지) in enumerate(정리):
        상자 += f'<i style="left:{x}%;top:{y}%;width:{w}%;height:{h}%"></i>'
        if 뱃지:
            # 번호 자리 — 왼쪽 옆 → 오른쪽 옆 → (둘 다 없으면) 상자 안쪽.
            # 나란히 붙은 두 상자에서는 왼쪽이 **옆 상자 안**이 된다 (아이콘 추가 ·
            # 커버 추가에서 실제로 ②가 ① 안에 들어가 앉았다). 그래서 비었는지 본다.
            # 번호는 26px 이 필요하다. 5% 처럼 **비율**로 재면 좁은 캡처에서
            # 그 5% 가 16px 밖에 안 돼 원이 그림 밖으로 나간다 (실제로 그랬다).
            여유칸 = 26.0 / max(그린폭, 1) * 100
            if x >= 여유칸 and _빈자리(x - 2.0, y, i):
                꼴, 가로 = "", x
            elif x + w <= 100.0 - 여유칸 and _빈자리(x + w + 2.0, y, i):
                꼴, 가로 = ' class="오른쪽"', x + w
            else:
                꼴, 가로 = ' class="안쪽"', x
            상자 += f'<b{꼴} style="left:{가로}%;top:{y}%">{뱃지}</b>'
    # 조망 = 전체 모양만 보는 장. 작은 글자를 읽을 필요가 없어 크기 검사에서 뺀다.
    표식 = ' data-view="1"' if 조망 else ""
    return f'<div class="shotbox"{표식} {크기}>{img}{상자}</div>'
